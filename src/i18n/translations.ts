export function translateText(source: string, language: Language) {
  if (language === "zh") {
    return source;
  }

  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const core = source.trim();

  if (!core) {
    return source;
  }

  const exact = translations[core]?.[language];

  if (exact) {
    return `${leading}${exact}${trailing}`;
  }

  const translated = Object.entries(translations)
    .filter(([phrase]) => phrase.length >= 2 && core.includes(phrase))
    .sort(([a], [b]) => b.length - a.length)
    .reduce((text, [phrase, values]) => text.split(phrase).join(values[language]), core);

  return `${leading}${translated}${trailing}`;
}
